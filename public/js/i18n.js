export const dictionaries = D;

function detect() {
  try {
    const saved = localStorage.getItem(STORE);
    if (LANGS.includes(saved)) return saved;
  } catch {}
  const nav = String((typeof navigator !== "undefined" && navigator.language) || "en").slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : "en";
}

let lang = detect();
export const getLang = () => lang;

export function t(key, params = {}) {
  const s = D[lang][key] ?? D.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : `{${k}}`));
}

/** Alle vertalingen van één sleutel (om te herkennen of een tekst nog de standaardtekst is). */
export const allValues = (key) => LANGS.map((l) => D[l][key]);

export function apply(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.setAttribute("title", t(el.dataset.i18nTitle));
  for (const b of root.querySelectorAll("[data-lang]")) b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return false;
  lang = next;
  try {
    localStorage.setItem(STORE, lang);
  } catch {}
  apply();
  return true;
}
